"""
Paper listing lst:ormatic: an EQL query of the running example evaluated in working memory and, translated to SQL by
ORMatic (current version, krrood.ormatic.eql_interface.eql_to_sql), in the database. Both must return the same students.

Uses the OWL2Bench-like model (owl2bench_like.py) and its DAOs (ormatic_interface.py, generated by generate_daos.py,
as main's test conftest does). Run in its own process: its Person/Student classes differ from test_listings.py's.
"""
from sqlalchemy.orm import Session, configure_mappers

from krrood.entity_query_language.factories import an, entity, variable
from krrood.ormatic.data_access_objects.helper import to_dao
from krrood.ormatic.data_access_objects.to_dao import ToDataAccessObjectState
from krrood.ormatic.eql_interface import eql_to_sql
from krrood.ormatic.utils import create_engine

import ormatic_interface
from owl2bench_like import Person, Student


def test_paper_ormatic_listing():
    ann, ben, cid = Person("Ann", has_age=30), Person("Ben", has_age=24), Person("Cid", has_age=40)
    students = [Student(role_taker=p) for p in (ann, ben, cid)]

    configure_mappers()
    engine = create_engine("sqlite:///:memory:")
    ormatic_interface.Base.metadata.create_all(engine)
    session = Session(engine)
    state = ToDataAccessObjectState()
    session.add_all(to_dao(x, state) for x in students)
    session.commit()

    # --- paper listing ---
    s = variable(Student, domain=students)  # all students
    over_25 = an(entity(s).where(s.has_age > 25))  # has_age: delegated to the role taker
    in_memory = list(over_25.evaluate())       # working memory
    stored = eql_to_sql(over_25, session,      # long-term memory
                        select_identifiers=True,
                        identifying_attribute="uri").evaluate()
    # --- end of paper listing ---

    translator = eql_to_sql(over_25, session, select_identifiers=True, identifying_attribute="uri")
    sql = str(translator.sql_query.compile(compile_kwargs={"literal_binds": True}))
    print("\nGenerated SQL:\n" + sql)
    assert sorted(x.uri for x in in_memory) == sorted(stored)
    assert sorted(x.role_taker.uri for x in in_memory) == ["Ann", "Cid"]
    assert "JOIN" in sql and "has_age > 25" in sql
